static double undefined_value(void){
#ifdef NAN
    return NAN;
#else
    volatile double z = 0.0;
    return z / z;
#endif
}

static int dataset_index(enum codata_dataset ds){
    int i;
    for(i = 0; i < CODATA_N_DATASETS; i++){
        if(datasets[i] == ds){return i;}
    }
    return -1;
}

const struct codata_constant_type *codata_get(enum codata_dataset ds, enum codata_quantity q){
    int i = dataset_index(ds);
    if(i < 0){return NULL;}
    if((int)q < 0 || (int)q >= CODATA_Q_COUNT){return NULL;}
    return tables[i][(int)q];
}

int codata_defined(enum codata_dataset ds, enum codata_quantity q){
    return codata_get(ds, q) != NULL;
}

double codata_value(enum codata_dataset ds, enum codata_quantity q){
    const struct codata_constant_type *c = codata_get(ds, q);
    return (c == NULL) ? undefined_value() : c->value;
}

double codata_uncertainty(enum codata_dataset ds, enum codata_quantity q){
    const struct codata_constant_type *c = codata_get(ds, q);
    return (c == NULL) ? undefined_value() : c->uncertainty;
}

const char *codata_unit(enum codata_dataset ds, enum codata_quantity q){
    const struct codata_constant_type *c = codata_get(ds, q);
    return (c == NULL) ? NULL : c->unit;
}

const char *codata_quantity_name(enum codata_quantity q){
    if((int)q < 0 || (int)q >= CODATA_Q_COUNT){return NULL;}
    return quantity_names[(int)q];
}

static int name_cmp(const void *a, const void *b){
    return strcmp((const char *)a, ((const struct codata_name_entry *)b)->name);
}

enum codata_quantity codata_quantity_from_name(const char *name){
    const struct codata_name_entry *e;
    if(name == NULL){return CODATA_Q_UNKNOWN;}
    e = (const struct codata_name_entry *)bsearch(name, name_table,
            sizeof(name_table) / sizeof(name_table[0]),
            sizeof(name_table[0]), name_cmp);
    return (e == NULL) ? CODATA_Q_UNKNOWN : (enum codata_quantity)e->q;
}

const enum codata_dataset *codata_datasets(int *n){
    if(n != NULL){*n = CODATA_N_DATASETS;}
    return datasets;
}

const struct codata_constant_type **codata_constants(enum codata_dataset ds){
    int i = dataset_index(ds);
    return (i < 0) ? NULL : cc_tables[i];
}
