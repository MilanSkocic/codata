function codata_get(ds, q)result(p)
!! Constant for a quantity in an adjustment, or null if it is absent.
integer(int32), intent(in) :: ds !! Adjustment, e.g. CODATA_2018.
integer(int32), intent(in) :: q  !! Quantity key, e.g. Q_BOHR_RADIUS.
type(codata_constant_type), pointer :: p !! Constant, or null.
integer(int32) :: i
p => null()
if(q < 0_int32 .or. q >= Q_COUNT)then
    return
end if
select case(ds)
case(CODATA_2010)
    i = idx_2010(q + 1_int32)
    if(i > 0_int32) p => cc_2010(i)
case(CODATA_2014)
    i = idx_2014(q + 1_int32)
    if(i > 0_int32) p => cc_2014(i)
case(CODATA_2018)
    i = idx_2018(q + 1_int32)
    if(i > 0_int32) p => cc_2018(i)
case(CODATA_2022)
    i = idx_2022(q + 1_int32)
    if(i > 0_int32) p => cc_2022(i)
end select
end function codata_get
!-----------------------------------------------------------------------
function codata_defined(ds, q)result(r)
!! Whether the quantity is present in that adjustment.
integer(int32), intent(in) :: ds !! Adjustment.
integer(int32), intent(in) :: q  !! Quantity key.
logical :: r !! True if present.
type(codata_constant_type), pointer :: p
p => codata_get(ds, q)
r = associated(p)
end function codata_defined
!-----------------------------------------------------------------------
function codata_value(ds, q)result(v)
!! Value, or a quiet NaN if the quantity is absent from that adjustment.
!! Never 0.0: a plausible-looking wrong number is the worst failure mode.
integer(int32), intent(in) :: ds !! Adjustment.
integer(int32), intent(in) :: q  !! Quantity key.
real(dp) :: v !! Value, or NaN.
type(codata_constant_type), pointer :: p
p => codata_get(ds, q)
if(associated(p))then
    v = p%value
else
    v = ieee_value(1.0_dp, ieee_quiet_nan)
end if
end function codata_value
!-----------------------------------------------------------------------
