function codata_quantity_from_name(nm)result(q)
!! Quantity with this key name, accepting renamed spellings too.
character(len=*), intent(in) :: nm !! Key name.
integer(int32) :: q !! Quantity key, or Q_UNKNOWN.
integer(int32) :: i
