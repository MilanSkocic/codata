function codata_quantity_name(q)result(nm)
!! Canonical key name of a quantity, blank if out of range.
!! Adjustment-independent; the name NIST gives the quantity in a
!! particular adjustment is the name component of the constant.
integer(int32), intent(in) :: q !! Quantity key.
character(len=64) :: nm !! Key name, or blank.
if(q < 0_int32 .or. q >= Q_COUNT)then
    nm = ""
else
    nm = quantity_names(q + 1_int32)
end if
end function codata_quantity_name
